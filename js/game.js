/**
 * "Contain the breach": a small pixel-art survival shooter below the footer
 * ------------------------------------------------------------------
 * Rogue processes (server boxes on spider legs) crawl in from the edges in
 * waves. You move with WASD or the arrow keys, aim with the mouse and click
 * (or hold) to shoot. Touching a bot costs a heart; lose all three and the
 * box is breached.
 *
 * Everything is drawn on one low-resolution canvas that CSS scales up with
 * crisp pixels (PIXEL screen pixels per game pixel). There are no image
 * files: the sand, rocks and sprites are generated by code below, shaded
 * with ordered (Bayer) dithering to get the grainy monochrome look.
 *
 * Order of this file:
 *   1. Palette and pixel helpers
 *   2. Terrain and rocks (drawn once per game onto an offscreen canvas)
 *   3. Sprites: player and the three bot types (pre-rendered frames)
 *   4. Sound effects (WebAudio, synthesised, mutable)
 *   5. Game state, waves and the update loop
 *   6. Drawing
 *   7. Input, HUD, overlays, pause handling
 *
 * Touch: hold a finger on the field to walk toward it; the player aims and
 * fires at the nearest bot automatically.
 */
(function () {
  'use strict';
  const root = document.getElementById('breach');
  if (!root) return;

  /* ---------- 1. Palette and pixel helpers ---------- */
  const C = {
    sand: ['#dcdcd8', '#cbcbc7', '#b6b6b1', '#9c9c96'],  // light to dark terrain tones
    rock: ['#ececE8', '#c6c6c1', '#9e9e98', '#73736d'],
    speck: '#7c7c76',
    white: '#f4f4f0',
    face: '#d4d4d0',
    side: '#9f9f9a',
    vent: '#6c6c66',
    ink: '#151515',
    jacket: '#3a3a38',
    grey: '#8a8a85',
    accent: '#FFB224'
  };
  // 4x4 Bayer matrix: thresholds for ordered dithering
  const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
  const dither = (x, y) => BAYER[(y & 3) * 4 + (x & 3)] / 16 - 0.5;
  const rnd = (a, b) => a + Math.random() * (b - a);
  const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

  const canvas = (w, h) => { const c = document.createElement('canvas'); c.width = w; c.height = h; return c; };
  const px = (g, x, y, col) => { g.fillStyle = col; g.fillRect(x | 0, y | 0, 1, 1); };
  // Bresenham line, one pixel wide
  const line = (g, x0, y0, x1, y1, col) => {
    x0 |= 0; y0 |= 0; x1 |= 0; y1 |= 0;
    const dx = Math.abs(x1 - x0), dy = -Math.abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1;
    let err = dx + dy;
    for (;;) {
      px(g, x0, y0, col);
      if (x0 === x1 && y0 === y1) break;
      const e2 = 2 * err;
      if (e2 >= dy) { err += dy; x0 += sx; }
      if (e2 <= dx) { err += dx; y0 += sy; }
    }
  };
  // Fill a polygon pixel by pixel (no anti-aliasing, so edges stay crisp)
  const poly = (g, pts, col) => {
    const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
    for (let y = Math.min(...ys); y <= Math.max(...ys); y++) {
      for (let x = Math.min(...xs); x <= Math.max(...xs); x++) {
        let inside = false;
        for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
          const [xi, yi] = pts[i], [xj, yj] = pts[j];
          if ((yi > y + 0.5) !== (yj > y + 0.5) && x + 0.5 < ((xj - xi) * (y + 0.5 - yi)) / (yj - yi) + xi) inside = !inside;
        }
        if (inside) px(g, x, y, col);
      }
    }
  };
  const outline = (g, pts, col) => pts.forEach((p, i) => { const q = pts[(i + 1) % pts.length]; line(g, p[0], p[1], q[0], q[1], col); });
  // Mirror a sprite frame for things walking left
  const flip = (src) => { const c = canvas(src.width, src.height), g = c.getContext('2d'); g.scale(-1, 1); g.drawImage(src, -src.width, 0); return c; };
  // Solid white copy of a frame, flashed when a bot is hit
  const silhouette = (src) => { const c = canvas(src.width, src.height), g = c.getContext('2d'); g.drawImage(src, 0, 0); g.globalCompositeOperation = 'source-in'; g.fillStyle = C.white; g.fillRect(0, 0, c.width, c.height); return c; };

  // Smooth value noise for the sand
  const makeNoise = () => {
    const seed = Array.from({ length: 4096 }, () => Math.random());
    const at = (x, y) => seed[((x & 63) * 64 + (y & 63)) & 4095];
    const smooth = (t) => t * t * (3 - 2 * t);
    return (x, y) => {
      const xi = Math.floor(x), yi = Math.floor(y), xf = smooth(x - xi), yf = smooth(y - yi);
      const a = at(xi, yi), b = at(xi + 1, yi), c = at(xi, yi + 1), d = at(xi + 1, yi + 1);
      return a + (b - a) * xf + (c - a) * yf + (a - b - c + d) * xf * yf;
    };
  };

  /* ---------- 2. Terrain and rocks ---------- */
  let W = 0, H = 0, terrain = null, cleanTerrain = null, rocks = [];

  const drawRock = (g, cx, cy, r, noise) => {
    const ry = r * 0.72;
    // shadow, dithered, down and to the right
    for (let y = -ry - 2; y <= ry + 3; y++) for (let x = -r - 2; x <= r + 4; x++) {
      const d = ((x - 2.5) / (r + 1)) ** 2 + ((y - 2) / (ry + 1)) ** 2;
      if (d < 1 && ((x + y) & 1)) px(g, cx + x, cy + y, C.sand[3]);
    }
    const inside = (x, y) => {
      const a = Math.atan2(y, x), wob = 1 + 0.18 * (noise(Math.cos(a) * 2 + cx, Math.sin(a) * 2 + cy) - 0.5) * 2;
      return (x / r) ** 2 + (y / ry) ** 2 < wob * wob;
    };
    for (let y = Math.floor(-ry * 1.3); y <= ry * 1.3; y++) for (let x = Math.floor(-r * 1.3); x <= r * 1.3; x++) {
      if (!inside(x, y)) continue;
      const edge = !inside(x + 1, y) || !inside(x - 1, y) || !inside(x, y + 1) || !inside(x, y - 1);
      if (edge) { px(g, cx + x, cy + y, (y > 0 || x > r * 0.3) ? C.ink : C.rock[3]); continue; }
      // lit from the top left
      const light = 1 - ((-x / r) * 0.55 + (-y / ry) * 0.75 + 1.3) / 2.6;
      const lvl = clamp(Math.floor(light * 4 + dither(cx + x, cy + y)), 0, 3);
      px(g, cx + x, cy + y, C.rock[lvl]);
    }
  };

  const buildTerrain = () => {
    const noise = makeNoise();
    const c = canvas(W, H), g = c.getContext('2d');
    const img = g.createImageData(W, H), d = img.data;
    const tones = C.sand.map((h) => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)]);
    const speck = [124, 124, 118], white = [244, 244, 240];
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      // layered noise plus long diagonal wind streaks
      let v = noise(x / 56, y / 56) * 0.6 + noise(x / 20, y / 20) * 0.3 + noise(x / 7, y / 7) * 0.1;
      v += 0.16 * Math.sin((x * 0.55 + y) / 15 + noise(x / 30, y / 30) * 5);
      const lvl = clamp(Math.floor((v - 0.08) * 3.2 + dither(x, y)), 0, 3);
      let col = tones[lvl];
      const r = Math.random();
      if (r < 0.004) col = speck; else if (r < 0.006) col = white;
      const i = (y * W + x) * 4;
      d[i] = col[0]; d[i + 1] = col[1]; d[i + 2] = col[2]; d[i + 3] = 255;
    }
    g.putImageData(img, 0, 0);
    // a few small craters
    for (let n = 0; n < Math.round(W * H / 9000); n++) {
      const cx = rnd(10, W - 10) | 0, cy = rnd(10, H - 10) | 0, r = rnd(2, 4) | 0;
      for (let a = 0; a < 6.28; a += 0.25) px(g, cx + Math.cos(a) * r, cy + Math.sin(a) * r * 0.6, a > 3.14 ? C.sand[3] : C.white);
    }
    // rocks, kept clear of the middle where the player starts
    rocks = [];
    const count = Math.round(W * H / 3600);
    for (let tries = 0; rocks.length < count && tries < 400; tries++) {
      const r = Math.random() < 0.25 ? rnd(6, 10) : rnd(2.5, 5);
      const x = rnd(r + 4, W - r - 4), y = rnd(r + 4, H - r - 4);
      if (Math.hypot(x - W / 2, y - H / 2) < 30) continue;
      if (rocks.some((o) => Math.hypot(o.x - x, o.y - y) < o.r + r + 10)) continue;
      rocks.push({ x, y, r });
    }
    rocks.sort((a, b) => a.y - b.y).forEach((o) => drawRock(g, Math.round(o.x), Math.round(o.y), o.r, noise));
    cleanTerrain = c;
    terrain = canvas(W, H);
    terrain.getContext('2d').drawImage(c, 0, 0);
  };

  // Scorch mark left on the sand where a bot died (until the next game)
  const scorch = (x, y, r) => {
    const g = terrain.getContext('2d');
    for (let j = -r; j <= r; j++) for (let i = -r; i <= r; i++) {
      const d = (i * i) / (r * r) + (j * j) / (r * r * 0.5);
      if (d > 1) continue;
      if (d < 0.35 && Math.random() < 0.5) px(g, x + i, y + j, C.ink);
      else if ((i + j) & 1) px(g, x + i, y + j, d < 0.7 ? C.vent : C.sand[3]);
    }
  };

  /* ---------- 3. Sprites ---------- */
  // Player: a tiny operator with an amber visor, drawn from character maps
  const PLAYER_FRAMES = [
    ['...KKK...', '..KWWWK..', '..KAAAK..', '..KWWWK..', '...KKK...', '..KDDDK..', '.KDDDDDK.', '.KDDGDDK.', '.KDDDDDK.', '..KDDDK..', '..KD.DK..', '..KD.DK..', '..KK.KK..'],
    ['...KKK...', '..KWWWK..', '..KAAAK..', '..KWWWK..', '...KKK...', '..KDDDK..', '.KDDDDDK.', '.KDDGDDK.', '.KDDDDDK.', '..KDDDK..', '.KD...DK.', '.KD...DK.', '.KK...KK.']
  ];
  const MAP = { K: C.ink, W: C.white, A: C.accent, D: C.jacket, G: C.grey };
  const fromMap = (rows) => {
    const c = canvas(rows[0].length, rows.length), g = c.getContext('2d');
    rows.forEach((row, y) => [...row].forEach((ch, x) => { if (MAP[ch]) px(g, x, y, MAP[ch]); }));
    return c;
  };
  const playerSprite = PLAYER_FRAMES.map(fromMap);
  const playerSpriteL = playerSprite.map(flip);

  // Bots: an isometric server box (front, side and top faces) on four pairs of legs.
  // Built once per type into four walking frames, plus mirrored and white-flash copies.
  const buildBot = ({ fw, fh, sw, th, leg }) => {
    const cw = fw + sw + leg * 2 + 4, ch = th + fh + leg + 6;
    const bx = leg + 2, by = 2;
    const frames = [];
    for (let f = 0; f < 4; f++) {
      const c = canvas(cw, ch), g = c.getContext('2d');
      const hipY = by + th + fh - 3;
      // legs: two on each side, alternating which pair is lifted each frame
      const hips = [[bx + 1, hipY, -1], [bx + 3, hipY + 1, -1], [bx + fw + sw - 1, hipY - sw + 1, 1], [bx + fw + 1, hipY + 1, 1]];
      hips.forEach(([hx, hy, dir], i) => {
        const up = (f + i) % 2 === 0, lift = up ? -2 : 0, step = (f % 2 ? 1 : -1) * (i % 2 ? 1 : -1);
        const kx = hx + dir * Math.round(leg * 0.55), ky = hy - Math.round(leg * 0.45) + (up ? -1 : 0);
        const fx = hx + dir * leg + step, fy = hy + Math.round(leg * 0.65) + lift;
        line(g, hx, hy, kx, ky, C.ink);
        line(g, kx, ky, fx, fy, C.ink);
        px(g, kx, ky - 1, C.grey);
      });
      const top = [[bx, by + th], [bx + fw, by + th], [bx + fw + sw, by], [bx + sw, by]];
      const front = [[bx, by + th], [bx + fw, by + th], [bx + fw, by + th + fh], [bx, by + th + fh]];
      const side = [[bx + fw, by + th], [bx + fw + sw, by], [bx + fw + sw, by + fh], [bx + fw, by + th + fh]];
      poly(g, top, C.white); poly(g, front, C.face); poly(g, side, C.side);
      // front details: vent slits and a tiny Chadbox mark with one amber pixel
      for (let v = by + th + 2; v < by + th + fh - 2; v += 2) line(g, bx + 2, v, bx + 2 + Math.max(1, Math.round(fw * 0.3)), v, C.vent);
      if (fw >= 8) {
        const mx = bx + fw - 5, my = by + th + 2;
        for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) if ((i + j) % 2 === 0) px(g, mx + i, my + j, i + j === 0 ? C.accent : C.vent);
      }
      for (let v = by + 3; v < by + fh - 1; v += 3) line(g, bx + fw + 1, v + th - 2, bx + fw + sw - 1, v + th - 2 - sw + 2, C.vent);
      outline(g, top, C.ink); outline(g, front, C.ink); outline(g, side, C.ink);
      frames.push(c);
    }
    // foot: sprite row where the feet touch the ground; mid: height of the body centre above the feet (for hits)
    const foot = by + th + fh - 3 + Math.round(leg * 0.65) + 1, mid = foot - (by + th + Math.round(fh / 2));
    return { frames, framesL: frames.map(flip), flash: frames.map(silhouette), flashL: frames.map(flip).map(silhouette), w: cw, h: ch, foot, mid };
  };
  const BOTS = {
    // hp: hits to destroy, r: hit radius, sp: base speed (game px per second), score: kill value
    worker: { ...buildBot({ fw: 10, fh: 10, sw: 4, th: 3, leg: 6 }), hp: 3, r: 7, sp: 20 },
    runner: { ...buildBot({ fw: 6, fh: 6, sw: 3, th: 2, leg: 5 }), hp: 1, r: 5, sp: 40 },
    rack: { ...buildBot({ fw: 15, fh: 16, sw: 6, th: 4, leg: 8 }), hp: 10, r: 11, sp: 12 }
  };

  /* ---------- 4. Sound effects ---------- */
  let audio = null, muted = false;
  try { muted = localStorage.getItem('chadbox-breach-muted') === '1'; } catch (e) { /* storage blocked */ }
  const sfx = (type) => {
    if (muted) return;
    try {
      audio = audio || new (window.AudioContext || window.webkitAudioContext)();
      const t = audio.currentTime, out = audio.createGain();
      out.connect(audio.destination);
      const tone = (wave, f0, f1, dur, vol) => {
        const o = audio.createOscillator(); o.type = wave;
        o.frequency.setValueAtTime(f0, t); o.frequency.exponentialRampToValueAtTime(f1, t + dur);
        out.gain.setValueAtTime(vol, t); out.gain.exponentialRampToValueAtTime(0.0001, t + dur);
        o.connect(out); o.start(t); o.stop(t + dur);
      };
      const noise = (dur, vol, cutoff) => {
        const b = audio.createBuffer(1, audio.sampleRate * dur, audio.sampleRate), d = b.getChannelData(0);
        for (let i = 0; i < d.length; i++) d[i] = (Math.random() * 2 - 1) * (1 - i / d.length);
        const s = audio.createBufferSource(), f = audio.createBiquadFilter();
        f.type = 'lowpass'; f.frequency.value = cutoff; s.buffer = b;
        out.gain.setValueAtTime(vol, t); out.gain.exponentialRampToValueAtTime(0.0001, t + dur);
        s.connect(f); f.connect(out); s.start(t);
      };
      if (type === 'shoot') tone('square', 900, 420, 0.06, 0.035);
      if (type === 'hit') tone('triangle', 300, 160, 0.05, 0.06);
      if (type === 'boom') noise(0.35, 0.22, 900);
      if (type === 'hurt') tone('sawtooth', 180, 50, 0.35, 0.09);
      if (type === 'wave') { tone('square', 523, 784, 0.25, 0.04); }
      if (type === 'over') tone('sawtooth', 220, 40, 0.9, 0.08);
    } catch (e) { /* audio unavailable */ }
  };

  /* ---------- 5. Game state, waves and update ---------- */
  const HEARTS = 3;
  const PLAYER_SPEED = 70, BULLET_SPEED = 250, FIRE_EVERY = 0.13;
  let player, bots = [], bullets = [], parts = [], toSpawn = 0, spawnIn = 0, between = 0, shake = 0, cooldown = 0;
  let wave = 1, kills = 0, alive = 0, hearts = HEARTS;
  let state = 'title';   // title | play | paused | over
  const input = { up: 0, down: 0, left: 0, right: 0, fire: false, mx: 0, my: 0, mouse: false, touch: null };

  // How each wave is made: more bots, faster spawns, tougher types later on
  const waveSize = (n) => 5 + (n - 1) * 3;
  const spawnGap = (n) => Math.max(0.3, 1.25 - n * 0.09);
  const pickType = (n) => {
    const r = Math.random();
    if (n >= 5 && r < Math.min(0.2, 0.05 * (n - 4))) return 'rack';
    if (n >= 3 && r < 0.45 && Math.random() < Math.min(0.4, 0.12 * (n - 2))) return 'runner';
    return 'worker';
  };

  const reset = () => {
    terrain.getContext('2d').drawImage(cleanTerrain, 0, 0);
    player = { x: W / 2, y: H / 2 + 6, face: 1, step: 0, inv: 0, aim: 0 };
    bots = []; bullets = []; parts = [];
    wave = 0; kills = 0; alive = 0; hearts = HEARTS; shake = 0; cooldown = 0;
    nextWave();
  };

  const nextWave = () => {
    wave += 1; toSpawn = waveSize(wave); spawnIn = 0.8; between = 0;
    if (wave > 1 && wave % 3 === 1) hearts = Math.min(HEARTS, hearts + 1);   // a heart back every third wave
    banner('Wave ' + wave);
    if (wave > 1) sfx('wave');
    hud();
  };

  const spawnBot = () => {
    const type = pickType(wave), T = BOTS[type], side = Math.floor(Math.random() * 4);
    const x = side === 0 ? -14 : side === 1 ? W + 14 : rnd(0, W);
    const y = side === 2 ? -6 : side === 3 ? H + 22 : rnd(10, H);
    bots.push({ type, T, x, y, vx: 0, vy: 0, hp: T.hp, flash: 0, dist: Math.random() * 12, face: 1, sp: T.sp * (1 + wave * 0.05) * rnd(0.9, 1.1) });
  };

  // Keep a circle out of the rocks
  const pushOut = (o, r) => {
    rocks.forEach((k) => {
      const dx = o.x - k.x, dy = o.y - k.y, d = Math.hypot(dx, dy), min = k.r + r;
      if (d < min && d > 0.01) { o.x = k.x + (dx / d) * min; o.y = k.y + (dy / d) * min; }
    });
  };

  const burst = (x, y, n, opts) => {
    for (let i = 0; i < n; i++) {
      const a = rnd(0, Math.PI * 2), s = rnd(opts.s0 || 20, opts.s1 || 70);
      parts.push({ x, y, vx: Math.cos(a) * s, vy: Math.sin(a) * s - (opts.up || 0), life: rnd(0.25, opts.life || 0.6), max: 0, col: opts.cols[i % opts.cols.length], kind: opts.kind || 'bit', r: opts.r || 0 });
      parts[parts.length - 1].max = parts[parts.length - 1].life;
    }
  };

  const nearestBot = () => {
    let best = null, bd = Infinity;
    bots.forEach((b) => { const d = Math.hypot(b.x - player.x, b.y - player.y); if (d < bd && b.x > 0 && b.x < W && b.y > 0 && b.y < H) { bd = d; best = b; } });
    return best;
  };

  const update = (dt) => {
    alive += dt;
    shake = Math.max(0, shake - dt * 20);
    player.inv = Math.max(0, player.inv - dt);

    // movement: keyboard, or walk toward a held finger on touch screens
    let mx = input.right - input.left, my = input.down - input.up;
    if (input.touch) {
      const dx = input.touch.x - player.x, dy = input.touch.y - player.y, d = Math.hypot(dx, dy);
      if (d > 6) { mx = dx / d; my = dy / d; }
    }
    const ml = Math.hypot(mx, my);
    if (ml > 0) {
      player.x += (mx / ml) * PLAYER_SPEED * dt; player.y += (my / ml) * PLAYER_SPEED * dt;
      player.step += PLAYER_SPEED * dt;
    }
    player.x = clamp(player.x, 6, W - 6); player.y = clamp(player.y, 14, H - 2);
    pushOut(player, 4);

    // aiming: mouse position, or the nearest bot on touch
    let target = null;
    if (input.touch) { const b = nearestBot(); if (b) target = { x: b.x, y: b.y - b.T.mid }; }
    else if (input.mouse) target = { x: input.mx, y: input.my };
    if (target) player.aim = Math.atan2(target.y - (player.y - 7), target.x - player.x);
    player.face = Math.cos(player.aim) < 0 ? -1 : 1;

    // shooting
    cooldown -= dt;
    if ((input.fire || (input.touch && target)) && cooldown <= 0) {
      cooldown = FIRE_EVERY;
      const ox = player.x + Math.cos(player.aim) * 6, oy = player.y - 7 + Math.sin(player.aim) * 6;
      bullets.push({ x: ox, y: oy, vx: Math.cos(player.aim) * BULLET_SPEED, vy: Math.sin(player.aim) * BULLET_SPEED, life: 1.2 });
      burst(ox, oy, 3, { cols: [C.accent, C.white], s0: 10, s1: 40, life: 0.12 });
      sfx('shoot');
    }

    // bullets
    for (const b of bullets) {
      b.x += b.vx * dt; b.y += b.vy * dt; b.life -= dt;
      if (b.x < -4 || b.x > W + 4 || b.y < -4 || b.y > H + 4) b.life = 0;
      if (rocks.some((k) => Math.hypot(b.x - k.x, b.y - k.y) < k.r)) { b.life = 0; burst(b.x, b.y, 4, { cols: [C.white, C.grey], s0: 15, s1: 45, life: 0.25 }); }
      if (b.life <= 0) continue;
      for (const e of bots) {
        const cy = e.y - e.T.mid;
        if (Math.hypot(b.x - e.x, b.y - cy) < e.T.r) {
          b.life = 0; e.hp -= 1; e.flash = 0.08;
          e.vx += (b.vx / BULLET_SPEED) * 45; e.vy += (b.vy / BULLET_SPEED) * 45;
          burst(b.x, b.y, 3, { cols: [C.accent, C.ink], s0: 20, s1: 60, life: 0.2 });
          sfx('hit');
          break;
        }
      }
    }
    bullets = bullets.filter((b) => b.life > 0);

    // spawning
    if (toSpawn > 0) {
      spawnIn -= dt;
      if (spawnIn <= 0) { spawnBot(); toSpawn -= 1; spawnIn = spawnGap(wave); }
    } else if (!bots.length) {
      between += dt;
      if (between > 1.4) nextWave();
    }

    // bots: walk toward the player, keep apart from each other, avoid rocks
    for (const e of bots) {
      const dx = player.x - e.x, dy = player.y - e.y, d = Math.hypot(dx, dy) || 1;
      let ax = (dx / d) * e.sp, ay = (dy / d) * e.sp;
      for (const o of bots) {
        if (o === e) continue;
        const ox = e.x - o.x, oy = e.y - o.y, od = Math.hypot(ox, oy);
        const min = (e.T.r + o.T.r) * 0.9;
        if (od < min && od > 0.01) { ax += (ox / od) * 40; ay += (oy / od) * 40; }
      }
      e.vx += (ax - e.vx) * Math.min(1, dt * 4); e.vy += (ay - e.vy) * Math.min(1, dt * 4);
      e.x += e.vx * dt; e.y += e.vy * dt;
      e.dist += Math.hypot(e.vx, e.vy) * dt;
      if (Math.abs(e.vx) > 2) e.face = e.vx < 0 ? -1 : 1;
      if (e.x > 0 && e.x < W && e.y > 0 && e.y < H) pushOut(e, e.T.r * 0.6);
      e.flash = Math.max(0, e.flash - dt);

      // touching the player costs a heart, then a short moment of invulnerability
      if (d < e.T.r + 3 && player.inv <= 0) {
        hearts -= 1; player.inv = 1.3; shake = 6;
        sfx('hurt'); hud();
        burst(player.x, player.y - 6, 10, { cols: [C.accent, C.ink, C.white], s0: 30, s1: 90 });
        bots.forEach((o) => { const kx = o.x - player.x, ky = o.y - player.y, kd = Math.hypot(kx, ky) || 1; if (kd < 40) { o.vx += (kx / kd) * 160; o.vy += (ky / kd) * 160; } });
        if (hearts <= 0) { gameOver(); return; }
      }
    }

    // destroyed bots: debris, smoke, a scorch mark on the sand
    bots = bots.filter((e) => {
      if (e.hp > 0) return true;
      kills += 1; shake = Math.max(shake, e.type === 'rack' ? 5 : 2.5);
      const cy = e.y - e.T.mid;
      burst(e.x, cy, e.type === 'rack' ? 26 : 14, { cols: [C.ink, C.face, C.white, C.vent, C.accent], s0: 25, s1: 110, up: 30, life: 0.7 });
      burst(e.x, cy, e.type === 'rack' ? 6 : 3, { cols: [C.vent], kind: 'smoke', s0: 4, s1: 14, life: 0.9, r: e.type === 'rack' ? 7 : 4 });
      scorch(Math.round(e.x), Math.round(e.y), e.type === 'rack' ? 9 : e.type === 'runner' ? 4 : 6);
      sfx('boom'); hud();
      return false;
    });

    // particles
    parts.forEach((p) => {
      p.life -= dt; p.x += p.vx * dt; p.y += p.vy * dt;
      p.vx *= 1 - dt * 3; p.vy = p.vy * (1 - dt * 3) + (p.kind === 'bit' ? 140 * dt : -6 * dt);
    });
    parts = parts.filter((p) => p.life > 0);
  };

  /* ---------- 6. Drawing ---------- */
  const view = document.getElementById('breach-canvas');
  const ctx = view.getContext('2d');

  const shadow = (x, y, rx) => {
    const ry = Math.max(1, Math.round(rx * 0.35));
    for (let j = -ry; j <= ry; j++) for (let i = -rx; i <= rx; i++) {
      if ((i * i) / (rx * rx) + (j * j) / (ry * ry) <= 1 && ((x + i + y + j) & 1)) px(ctx, x + i, y + j, C.sand[3]);
    }
  };

  const draw = () => {
    const sx = shake ? Math.round(rnd(-shake, shake)) : 0, sy = shake ? Math.round(rnd(-shake, shake)) : 0;
    ctx.setTransform(1, 0, 0, 1, sx, sy);
    ctx.drawImage(terrain, 0, 0);
    if (state === 'title') return;

    // bots and player, back to front
    const things = bots.map((e) => ({ y: e.y, e })).concat([{ y: player.y, p: true }]).sort((a, b) => a.y - b.y);
    things.forEach((t) => {
      if (t.p) {
        const x = Math.round(player.x), y = Math.round(player.y);
        shadow(x, y, 4);
        if (player.inv > 0 && Math.floor(player.inv * 10) % 2) return;   // blink while invulnerable
        const fr = Math.floor(player.step / 6) % 2;
        const spr = player.face < 0 ? playerSpriteL[fr] : playerSprite[fr];
        ctx.drawImage(spr, x - 4, y - 13);
        // the gun: a short amber line pointing where you aim
        line(ctx, x + Math.cos(player.aim) * 2, y - 7 + Math.sin(player.aim) * 2, x + Math.cos(player.aim) * 6, y - 7 + Math.sin(player.aim) * 6, C.ink);
        px(ctx, x + Math.cos(player.aim) * 6, y - 7 + Math.sin(player.aim) * 6, C.accent);
        return;
      }
      const e = t.e, T = e.T, fr = Math.floor(e.dist / 3) % 4;
      const x = Math.round(e.x), y = Math.round(e.y);
      shadow(x, y, Math.round(T.w * 0.32));
      const left = e.face < 0;
      const spr = e.flash > 0 ? (left ? T.flashL[fr] : T.flash[fr]) : (left ? T.framesL[fr] : T.frames[fr]);
      ctx.drawImage(spr, x - Math.round(T.w / 2), y - T.foot);
    });

    // bullets with a short trail
    bullets.forEach((b) => {
      const tx = b.x - (b.vx / BULLET_SPEED) * 3, ty = b.y - (b.vy / BULLET_SPEED) * 3;
      px(ctx, tx, ty, C.grey);
      ctx.fillStyle = C.accent; ctx.fillRect(Math.round(b.x) - 1, Math.round(b.y) - 1, 2, 2);
      px(ctx, b.x, b.y, C.ink);
    });

    // particles: single-pixel debris and dithered smoke puffs
    parts.forEach((p) => {
      const k = p.life / p.max;
      if (p.kind === 'smoke') {
        const r = Math.round(p.r * (1.6 - k)), x = Math.round(p.x), y = Math.round(p.y);
        for (let j = -r; j <= r; j++) for (let i = -r; i <= r; i++) {
          if (i * i + j * j > r * r) continue;
          const keep = k > 0.5 ? (i + j) & 1 : !((i & 1) || (j & 1));
          if (keep) px(ctx, x + i, y + j, p.col);
        }
      } else px(ctx, p.x, p.y, p.col);
    });

    // crosshair at the mouse
    if (input.mouse && state === 'play') {
      const x = Math.round(input.mx), y = Math.round(input.my);
      line(ctx, x - 5, y, x - 2, y, C.ink); line(ctx, x + 2, y, x + 5, y, C.ink);
      line(ctx, x, y - 5, x, y - 2, C.ink); line(ctx, x, y + 2, x, y + 5, C.ink);
      px(ctx, x, y, C.accent);
    }
  };

  /* ---------- 7. Input, HUD, overlays, pause ---------- */
  const $ = (id) => document.getElementById(id);
  const heartsEl = $('breach-hearts'), waveEl = $('breach-wave'), killsEl = $('breach-kills'), timeEl = $('breach-time');
  const overlay = $('breach-overlay'), title = $('breach-title'), text = $('breach-text'), startBtn = $('breach-start');
  const bannerEl = $('breach-banner'), muteBtn = $('breach-mute');

  const fmt = (s) => Math.floor(s / 60) + ':' + String(Math.floor(s % 60)).padStart(2, '0');
  const hud = () => {
    heartsEl.textContent = '♥'.repeat(Math.max(0, hearts)) + '♡'.repeat(Math.max(0, HEARTS - hearts));
    heartsEl.setAttribute('aria-label', hearts + ' of ' + HEARTS + ' hearts');
    waveEl.textContent = 'Wave ' + wave;
    killsEl.textContent = kills;
    timeEl.textContent = fmt(alive);
  };
  let bannerTimer = 0;
  const banner = (msg) => {
    bannerEl.textContent = msg;
    bannerEl.classList.remove('show'); void bannerEl.offsetWidth; bannerEl.classList.add('show');
    clearTimeout(bannerTimer); bannerTimer = setTimeout(() => bannerEl.classList.remove('show'), 1400);
  };
  const showOverlay = (t, body, btn) => { title.textContent = t; text.textContent = body; startBtn.textContent = btn; overlay.hidden = false; };

  let best = { wave: 0, kills: 0 };
  try { best = JSON.parse(localStorage.getItem('chadbox-breach-best')) || best; } catch (e) { /* storage blocked */ }

  const gameOver = () => {
    state = 'over'; sfx('over');
    const isBest = wave > best.wave || (wave === best.wave && kills > best.kills);
    if (isBest) { best = { wave, kills }; try { localStorage.setItem('chadbox-breach-best', JSON.stringify(best)); } catch (e) { /* storage blocked */ } }
    showOverlay('Breached', 'You held ' + wave + (wave === 1 ? ' wave' : ' waves') + ', destroyed ' + kills + (kills === 1 ? ' bot' : ' bots') + ' and lasted ' + fmt(alive) + '.' + (isBest ? ' New best!' : ' Best: wave ' + best.wave + ', ' + best.kills + ' bots.'), 'Play again');
  };

  const start = () => {
    if (state === 'paused') { state = 'play'; overlay.hidden = true; root.focus({ preventScroll: true }); return; }
    reset(); state = 'play'; overlay.hidden = true;
    root.focus({ preventScroll: true });
  };
  const pause = () => {
    if (state !== 'play') return;
    state = 'paused';
    Object.assign(input, { up: 0, down: 0, left: 0, right: 0, fire: false, touch: null });
    showOverlay('Paused', 'Click resume to keep holding the line.', 'Resume');
  };

  // Size the game: one game pixel = PIXEL screen pixels, so the art stays crisp
  const size = () => {
    const r = view.parentElement.getBoundingClientRect();
    const PIXEL = r.width > 900 ? 4 : r.width > 520 ? 3 : 2;
    const w = Math.round(r.width / PIXEL), h = Math.round(r.height / PIXEL);
    if (w === W && h === H) return;
    if (state === 'play' || state === 'paused') return;   // keep the field stable mid-game; CSS scales it
    W = w; H = h; view.width = W; view.height = H;
    buildTerrain();
    draw();
  };

  // Keyboard only while the game has focus, so the page still scrolls normally otherwise
  const KEYS = { KeyW: 'up', ArrowUp: 'up', KeyS: 'down', ArrowDown: 'down', KeyA: 'left', ArrowLeft: 'left', KeyD: 'right', ArrowRight: 'right' };
  root.addEventListener('keydown', (e) => {
    if (KEYS[e.code] && state === 'play') { input[KEYS[e.code]] = 1; e.preventDefault(); }
    if (e.code === 'Space' && state === 'play') { input.fire = true; e.preventDefault(); }
    if ((e.code === 'Enter' || e.code === 'Space') && state !== 'play' && e.target.tagName !== 'BUTTON') { start(); e.preventDefault(); }
    if (e.code === 'Escape') pause();
  });
  root.addEventListener('keyup', (e) => {
    if (KEYS[e.code]) input[KEYS[e.code]] = 0;
    if (e.code === 'Space') input.fire = false;
  });
  root.addEventListener('focusout', (e) => { if (!root.contains(e.relatedTarget)) pause(); });

  const toGame = (e) => {
    const r = view.getBoundingClientRect();
    return { x: ((e.clientX - r.left) / r.width) * W, y: ((e.clientY - r.top) / r.height) * H };
  };
  view.addEventListener('pointermove', (e) => {
    const p = toGame(e);
    if (e.pointerType === 'touch') { if (input.touch) input.touch = p; return; }
    input.mouse = true; input.mx = p.x; input.my = p.y;
  });
  view.addEventListener('pointerleave', () => { input.mouse = false; input.fire = false; });
  // Clicking the canvas must not move keyboard focus away from the game
  view.addEventListener('mousedown', (e) => e.preventDefault());
  view.addEventListener('pointerdown', (e) => {
    e.preventDefault();
    if (state !== 'play') return;
    root.focus({ preventScroll: true });
    if (e.pointerType === 'touch') { input.touch = toGame(e); view.setPointerCapture(e.pointerId); return; }
    input.fire = true;
  });
  window.addEventListener('pointerup', () => { input.fire = false; input.touch = null; });

  startBtn.addEventListener('click', start);
  const setMute = (m) => {
    muted = m; muteBtn.textContent = m ? 'Unmute' : 'Mute'; muteBtn.setAttribute('aria-pressed', String(m));
    try { localStorage.setItem('chadbox-breach-muted', m ? '1' : '0'); } catch (e) { /* storage blocked */ }
  };
  muteBtn.addEventListener('click', () => { setMute(!muted); root.focus({ preventScroll: true }); });
  setMute(muted);

  // Pause when the game scrolls out of view or the tab is hidden
  if ('IntersectionObserver' in window) new IntersectionObserver((en) => { if (!en[0].isIntersecting) pause(); }, { threshold: 0.2 }).observe(root);
  document.addEventListener('visibilitychange', () => { if (document.hidden) pause(); });
  if ('ResizeObserver' in window) new ResizeObserver(size).observe(view.parentElement);
  else window.addEventListener('resize', size);

  // Main loop: fixed small steps for steady physics, drawn every frame
  let last = 0, hudTick = 0;
  const frame = (now) => {
    const dt = last ? Math.min((now - last) / 1000, 0.05) : 0;
    last = now;
    if (state === 'play') {
      update(dt);
      hudTick += dt;
      if (hudTick > 0.25) { hudTick = 0; timeEl.textContent = fmt(alive); }
    }
    if (W) draw();
    requestAnimationFrame(frame);
  };

  size();
  hud();
  requestAnimationFrame(frame);
})();
